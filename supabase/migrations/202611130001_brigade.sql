-- Own-auth brigade data. No app data are visible through anon/authenticated PostgREST.
CREATE SCHEMA IF NOT EXISTS brigade;
REVOKE ALL ON SCHEMA brigade FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA brigade TO service_role;
CREATE TABLE brigade."profiles" (
	"id" text PRIMARY KEY NOT NULL,
	"login" text NOT NULL,
	"password_hash" text NOT NULL,
	"nickname" text NOT NULL,
	"position" text NOT NULL,
	"grade" bigint,
	"avatar_media_id" text,
	"created_at" bigint NOT NULL,
	"updated_at" bigint NOT NULL,
	CONSTRAINT "profiles_position" CHECK("profiles"."position" IN ('operator','master')),
	CONSTRAINT "profiles_grade" CHECK("profiles"."grade" IS NULL OR "profiles"."grade" BETWEEN 3 AND 6)
);
CREATE TABLE brigade."chat_messages" (
	"seq" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
	"id" text NOT NULL,
	"user_id" text NOT NULL,
	"client_id" text NOT NULL,
	"body" text NOT NULL,
	"media_ids" text DEFAULT '[]' NOT NULL,
	"created_at" bigint NOT NULL,
	"updated_at" bigint NOT NULL,
	"revision" bigint DEFAULT 1 NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action
);


CREATE UNIQUE INDEX "chat_messages_id_unique" ON brigade."chat_messages" ("id");

CREATE UNIQUE INDEX "chat_messages_user_client" ON brigade."chat_messages" ("user_id","client_id");

CREATE TABLE brigade."media" (
	"id" text PRIMARY KEY NOT NULL,
	"owner_id" text NOT NULL,
	"bucket_key" text NOT NULL,
	"mime_type" text NOT NULL,
	"size" bigint NOT NULL,
	"created_at" bigint NOT NULL,
	"client_id" text,
	"content_hash" text NOT NULL,
	FOREIGN KEY ("owner_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action,
	CONSTRAINT "media_size" CHECK("media"."size">0 AND "media"."size"<=2097152)
);


CREATE UNIQUE INDEX "media_bucket_key_unique" ON brigade."media" ("bucket_key");

CREATE UNIQUE INDEX "media_owner_client" ON brigade."media" ("owner_id","client_id");

CREATE INDEX "media_owner" ON brigade."media" ("owner_id");

CREATE TABLE brigade."notifications" (
	"seq" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
	"id" text NOT NULL,
	"recipient_id" text NOT NULL,
	"actor_id" text NOT NULL,
	"type" text NOT NULL,
	"object_key" text NOT NULL,
	"object_label" text NOT NULL,
	"note_id" text NOT NULL,
	"parent_id" text NOT NULL,
	"preview" text NOT NULL,
	"created_at" bigint NOT NULL,
	"read_at" bigint,
	FOREIGN KEY ("recipient_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action,
	FOREIGN KEY ("actor_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action
);


CREATE UNIQUE INDEX "notifications_id_unique" ON brigade."notifications" ("id");

CREATE UNIQUE INDEX "notifications_recipient_note" ON brigade."notifications" ("recipient_id","note_id");

CREATE INDEX "notifications_recipient_seq" ON brigade."notifications" ("recipient_id","seq");

CREATE INDEX "notifications_recipient_read" ON brigade."notifications" ("recipient_id","read_at");

CREATE TABLE brigade."object_notes" (
	"seq" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
	"id" text NOT NULL,
	"object_key" text NOT NULL,
	"parent_id" text,
	"user_id" text NOT NULL,
	"client_id" text NOT NULL,
	"body" text NOT NULL,
	"media_ids" text DEFAULT '[]' NOT NULL,
	"created_at" bigint NOT NULL,
	"updated_at" bigint NOT NULL,
	"revision" bigint DEFAULT 1 NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action
);


CREATE UNIQUE INDEX "object_notes_id_unique" ON brigade."object_notes" ("id");

CREATE UNIQUE INDEX "object_notes_user_client" ON brigade."object_notes" ("user_id","client_id");

CREATE INDEX "object_notes_object_seq" ON brigade."object_notes" ("object_key","seq");

CREATE INDEX "object_notes_parent" ON brigade."object_notes" ("parent_id");

CREATE TABLE brigade."object_statuses" (
	"object_key" text PRIMARY KEY NOT NULL,
	"status" text NOT NULL,
	"note" text DEFAULT '' NOT NULL,
	"revision" bigint NOT NULL,
	"updated_at" bigint NOT NULL,
	"updated_by" text NOT NULL,
	"mutation_id" text NOT NULL,
	FOREIGN KEY ("updated_by") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action,
	CONSTRAINT "object_status_value" CHECK("object_statuses"."status" IN ('unknown','ok','attention','stopped'))
);





CREATE UNIQUE INDEX "profiles_login_unique" ON brigade."profiles" ("login");

CREATE TABLE brigade."push_subscriptions" (
	"id" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"endpoint" text NOT NULL,
	"p256dh" text NOT NULL,
	"auth" text NOT NULL,
	"created_at" bigint NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action
);


CREATE UNIQUE INDEX "push_subscriptions_endpoint_unique" ON brigade."push_subscriptions" ("endpoint");

CREATE INDEX "push_subscriptions_user" ON brigade."push_subscriptions" ("user_id");

CREATE TABLE brigade."rate_limits" (
	"key" text PRIMARY KEY NOT NULL,
	"count" bigint NOT NULL,
	"expires_at" bigint NOT NULL
);


CREATE INDEX "rate_limits_expiry" ON brigade."rate_limits" ("expires_at");

CREATE TABLE brigade."sample_audit" (
	"id" text PRIMARY KEY NOT NULL,
	"pad_id" text NOT NULL,
	"sampled" bigint NOT NULL,
	"note" text NOT NULL,
	"revision" bigint NOT NULL,
	"user_id" text NOT NULL,
	"created_at" bigint NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action
);


CREATE INDEX "sample_audit_pad_revision" ON brigade."sample_audit" ("pad_id","revision");

CREATE TABLE brigade."samples" (
	"pad_id" text PRIMARY KEY NOT NULL,
	"sampled" bigint NOT NULL,
	"note" text DEFAULT '' NOT NULL,
	"revision" bigint NOT NULL,
	"updated_at" bigint NOT NULL,
	"updated_by" text NOT NULL,
	"mutation_id" text NOT NULL,
	FOREIGN KEY ("updated_by") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action,
	CONSTRAINT "samples_sampled" CHECK("samples"."sampled" IN (0,1))
);


CREATE TABLE brigade."sessions" (
	"token_hash" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"created_at" bigint NOT NULL,
	"expires_at" bigint NOT NULL,
	"revoked_at" bigint,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE cascade
);


CREATE INDEX "sessions_user_created" ON brigade."sessions" ("user_id","created_at");

CREATE INDEX "sessions_expiry" ON brigade."sessions" ("expires_at");

CREATE TABLE brigade."shifts" (
	"id" text PRIMARY KEY NOT NULL,
	"user_id" text NOT NULL,
	"date" text NOT NULL,
	"kind" text NOT NULL,
	"note" text DEFAULT '' NOT NULL,
	"created_at" bigint NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action,
	CONSTRAINT "shifts_kind" CHECK("shifts"."kind" IN ('day','night'))
);


CREATE UNIQUE INDEX "shifts_user_date_kind" ON brigade."shifts" ("user_id","date","kind");

CREATE INDEX "shifts_date" ON brigade."shifts" ("date");

CREATE TABLE brigade."status_audit" (
	"id" text PRIMARY KEY NOT NULL,
	"object_key" text NOT NULL,
	"status" text NOT NULL,
	"note" text NOT NULL,
	"revision" bigint NOT NULL,
	"user_id" text NOT NULL,
	"created_at" bigint NOT NULL,
	FOREIGN KEY ("user_id") REFERENCES brigade."profiles"("id") ON UPDATE no action ON DELETE no action
);


